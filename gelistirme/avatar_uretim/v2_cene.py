"""Extract registered jaw clips from the shipped 512px grayscale face assets.

Alpha gives the outer jaw away from the neck. Across the neck, follow the
original dark chin line near a smooth interpolation between those boundaries
and the center chin. No face artwork is changed. Run with standard Python+PIL.
"""
from pathlib import Path
from PIL import Image
from statistics import median

ROOT = Path(__file__).resolve().parents[2]
SHAPES = ('oval', 'round', 'long', 'square', 'heart', 'wide')

def extract(shape):
    im = Image.open(ROOT / f'public/av/base/base_{shape}.webp').convert('RGBA')
    def lum(x, y):
        r, g, b, _ = im.getpixel((x,y))
        return .2126*r + .7152*g + .0722*b
    center = min(range(292, 322), key=lambda y: sum(lum(x,y) for x in range(249,264)))
    def outside(x):
        # First transparent pixel beneath cheek, before old shirt starts.
        return next((y for y in range(260, 324) if im.getpixel((x,y))[3] < 50), 323)
    left, right = outside(210), outside(300)
    points = []
    for x in range(160, 351, 2):
        if x <= 210 or x >= 300:
            y = outside(x)
        else:
            edge, width = (left,45) if x <= 255 else (right,45)
            estimate = center - (center-edge)*((x-255)/width)**2
            candidates = range(max(276,round(estimate)-4), min(324,round(estimate)+5))
            y = min(candidates, key=lambda yy: lum(x,yy) + abs(yy-estimate)*1.5) + 1
        points.append((x,y))
    # Reject isolated neck-outline branches at the two original jaw joins.
    clean = [(x, float(median([p[1] for p in points[max(0,i-4):i+5]])))
             for i,(x,y) in enumerate(points)]
    return [(x, round(sum(p[1] for p in clean[max(0,i-1):i+2]) / len(clean[max(0,i-1):i+2]), 2))
            for i,(x,y) in enumerate(clean)]

lines = ['// Generated by gelistirme/avatar_uretim/v2_cene.py from native face pixels.',
         '// Source coordinates in the original 512px portrait; only head/features use these.',
         'export const POSE_JAWS: Record<string, [number, number][]> = {']
for shape in SHAPES:
    points = extract(shape)
    lines.append(f'  {shape}: [' + ','.join(f'[{x},{y}]' for x,y in points) + '],')
lines.append('}\n')
(ROOT/'src/avatar/poseV2Jaw.ts').write_text('\n'.join(lines))
for shape in SHAPES:
    points = extract(shape)
    print(shape, 'chin', max(y for x,y in points if 225<x<285), 'neck joins', [p for p in points if p[0] in (210,300)])
